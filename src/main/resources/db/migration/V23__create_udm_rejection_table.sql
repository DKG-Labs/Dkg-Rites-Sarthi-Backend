CREATE TABLE IF NOT EXISTS udm_rejection (
    id                      BIGINT          AUTO_INCREMENT PRIMARY KEY,
    po_number               VARCHAR(50),
    po_date                 DATETIME,
    pl_number               VARCHAR(50),
    po_serial_number        VARCHAR(20),
    rejection_number        VARCHAR(100)    NOT NULL,
    rejection_date          DATETIME,
    type_of_rejection       VARCHAR(100),
    rejected_qty            DECIMAL(15, 3),
    uom                     VARCHAR(30),
    reason_for_rejection    TEXT,
    rejection_value         DECIMAL(18, 2),
    status                  VARCHAR(20),
    item_description        TEXT,
    ic_number               VARCHAR(100),
    ic_date                 DATETIME,
    inspection_agency       VARCHAR(100),
    vendor_code             VARCHAR(50),
    vendor_name             VARCHAR(255),
    consignee               VARCHAR(500),
    material_received_date  DATETIME,
    source                  VARCHAR(50),
    pdf_path                VARCHAR(500),
    fetched_date            DATE            NOT NULL,
    created_at              DATETIME        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_rejection_number UNIQUE (rejection_number),
    INDEX idx_po_number     (po_number),
    INDEX idx_vendor_code   (vendor_code),
    INDEX idx_rejection_date (rejection_date),
    INDEX idx_fetched_date  (fetched_date),
    INDEX idx_ic_number     (ic_number)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
